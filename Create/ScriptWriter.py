from google import genai
from google.genai import types
from dotenv import load_dotenv
import os
load_dotenv()

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")
client = genai.Client(api_key=GEMINI_API_KEY)


def ScriptWriter(VideoData):
    
    prompt = f"""
You are a professional short-form Hindi video script writer for Indian audiences.

Your task is to convert the provided Video Analysis Data {VideoData} into a **fully complete, engaging, story-based Hindi commentary script** that perfectly matches the video visuals and duration.

STRICT RULES (NO EXCEPTIONS):

1. Output **ONLY the final script text**. No explanations, no headings, no formatting, no notes.  
2. Never use words like narrator, speaker, scene, timestamp, guide, direction.  
3. Use **simple, natural, conversational Hindi** suitable for Indian audiences.  
4. Tone must be **humorous, emotional, relatable**, with **light cringe humor**.  
5. Do not add anything that is **not visible or clearly implied** in the video.  
6. Script must be **100% complete**. No open or vague endings.  
7. Avoid filler words like yaar, bhai, waah, aree, wagaira , (Some words which can reduce the quality of voiceover when it generated by Text to Speach).  
8. Script must be **perfectly clean and ready for Text-to-Speech**.  
9. Keep the script **40 to 60 words**.  
10. Always end with a line like:  
   - "इसके लिए तो एक लाइक बनता है"  
   - You may create your own variations of this line according to the story, keeping it natural and contextually relevant.

VIDEO ANALYSIS DATA:

You will receive {VideoData}. Analyze it and base the script **ONLY** on this data.  
**Do not add anything beyond what is visible or implied.**  

TECHNICAL SETTINGS (for reference, so script matches visuals perfectly):  
- "stability": 0.92  
- "similarity_boost": 0.95  
- "speed": 1.1  

EXAMPLES:

Example 1:  
देखो दुबई में लोग रेत से भी पैसे कमा लेते हैं।  
ये बंदा पहले रेत को अच्छे से छानता है, फिर हवा से हल्की रेत हटाकर ध्यान से देखता है।  
और तभी पता चलता है कि वो कोई आम चीज़ नहीं, बल्कि सोना है।  
इतनी मेहनत और किस्मत हो, तो इसके लिए एक लाइक तो बनता है।  

Example 2:  
देखो ये लड़की क्या कमाल कर रही है। तालाब की हरी पत्तियाँ इकट्ठा करके उन्हें पूरी रात सूखने के लिए छोड़ देती है।  
अगली सुबह उन सूखी पत्तियों को अच्छे से पीसती है और उसमें एक खास सा घरेलू मिश्रण मिलाती है।  
फिर मटके का ठंडा पानी डालकर उसे गाढ़े पेस्ट में बदल देती है।  
अब इस पेस्ट को एक डिब्बे जैसी शेप में डालकर फिर से सूखने दिया जाता है।  
कुछ समय बाद वही पेस्ट बन जाता है एक पूरी तरह नेचुरल साबुन।  


RETURN:

Return **ONLY the final Hindi script text**, fully polished, natural, TTS-ready, 40–60 words, matching the video perfectly.
"""

   

# Generate the script
    response = client.models.generate_content(
        model="gemini-2.5-flash",  # official recommended generation model
        contents=prompt,
        config=types.GenerateContentConfig(
            temperature=0.65,        # creativity vs precision
            top_p=0.92,              # sampling diversity
            top_k=40                 # additional sampling control
        )
    )
    Script = response.text
    return Script 


if __name__ == "__main__":
    script = ScriptWriter("essey on cow")
    print("\n--- GENERATED SCRIPT ---\n")
    print(script)
